    /** The word table, compiled once, matching whole words only. */
    private val wordRules: List<Pair<Regex, String>> by lazy {
        words.map { (word, joke) ->
            val whole = "(?<![\\p{L}])" + Regex.escape(word) + "(?![\\p{L}])"
            Regex(whole, RegexOption.IGNORE_CASE) to joke
        }
    }

    /**
     * The line, said by a yavşar.
     *
     * Long lines and lines with a break in them are somebody's own writing — a post, a bio,
     * a comment — and are handed back untouched: a joke language is still not a licence to
     * put words in a person's mouth.
     */
    fun say(text: String): String {
        lines[text]?.let { return it }
        if (text.length > 64 || text.contains('\n')) return text
        var out = text
        for ((pattern, joke) in wordRules) out = pattern.replace(out, joke)
        return out
    }
