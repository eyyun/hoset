/** Which gallery category a kit belongs to. */
enum class KitCategory {
    SIMPLE,
    DETAILED,
}

/** The motion personality this kit gives to interactive elements and surfaces. */
enum class KitMotion {
    NONE,      // Sakin
    PULSE,     // Işıma
    SHIFT,     // Gradyan
    BOUNCE,    // Yaylanan
    FLOAT,     // Süzülen
    RIPPLE,    // Dalgalanan
    NEON,      // Neon Akış
}

/** Surface styling hierarchy: solid, gradient, glow, glass, metallic, or neon border. */
enum class SurfaceEffect {
    SOLID,
    GRADIENT,
    GLOW,
    GLASS,
    METALLIC,
    NEON_BORDER,
}

/**
 * One look for the whole app: the fourteen colours every screen draws from.
 *
 * The first entry is the app's original look, read straight out of the website's own
 * stylesheets:
 *
 *  - themes/midnight.css  -> --bs-body-bg: #0d1117, --bs-body-secondary-bg: #161b22,
 *                            --bs-border-color: #262b32, --bs-body-color: #c9d1d9
 *  - <html style="--primary:#805ad5">  -> the favicon/purple accent
 *  - main.css             -> --downvote-color: #38b2ac
 *  - themes/midnight.css  -> --bs-orange: #fd7e14 (the upvote arrow colour)
 *
 * The rest are alternatives in the same shape — six dark, four light — so the app can be
 * something other than the site's own theme without any screen knowing which is on.
 */
data class Palette(
    val id: String,
    val name: String,

    /** The icon the kit wears in the store, and in the settings row once it is picked. */
    val icon: ImageVector,
    /** Light palettes need a light Material scheme under them; the dark ones do not. */
    val dark: Boolean,

    /**
     * How round the kit is. Three radii cover the app: cards and sheets, the controls on
     * them, and the small chips inside — so a kit can look soft or sharp without any
     * screen knowing which one is on.
     */
    val cardRadius: Dp,
    val controlRadius: Dp,
    val smallRadius: Dp,

    /** The weight this kit gives to titles. */
    val titleWeight: FontWeight,

    /**
     * The rest of what makes a kit a kit rather than a colour scheme: how surfaces are
     * drawn, how round an avatar is, how buttons are painted, whether lists are separated
     * by lines, how much air their rows get and how wide the letter spacing runs.
     */
    val cardStyle: CardStyle,
    val avatarShape: AvatarShape,
    val buttonStyle: ButtonStyle,
    val dividers: Boolean,
    val spacing: Dp,
    val letterSpacing: TextUnit,
    val background: Color,
    val surface: Color,
    val surfaceVariant: Color,
    val border: Color,
    val onBackground: Color,
    val onSurfaceVariant: Color,
    val primary: Color,
    val primaryContainer: Color,
    val blue: Color,
    val upvote: Color,
    val downvote: Color,
    val success: Color,
    val warning: Color,
    val danger: Color,
    val category: KitCategory = KitCategory.SIMPLE,
    val motion: KitMotion = KitMotion.NONE,
    val surfaceEffect: SurfaceEffect = SurfaceEffect.SOLID,
    val glowColor: Color = Color.Transparent,
    val gradientEnd: Color = surface,
)

